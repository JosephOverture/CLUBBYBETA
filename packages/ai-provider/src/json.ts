/**
 * Extract the first balanced top-level JSON object from a model response.
 * Models sometimes wrap JSON in prose or code fences; we scan for the first
 * `{ ... }` with balanced braces (ignoring braces inside strings).
 */
export function firstJsonObject(text: string): string {
  let depth = 0;
  let start = -1;
  let inString = false;
  let escaped = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') {
      inString = true;
    } else if (ch === '{') {
      if (depth === 0) start = i;
      depth += 1;
    } else if (ch === '}') {
      depth -= 1;
      if (depth === 0 && start >= 0) return text.slice(start, i + 1);
    }
  }
  throw new Error('No JSON object found in model response.');
}
